package main;

public class Exercicio01 {
	public static void main(String[] args) {

		//converta para as classes involucro
		
		int valor = 1; // Integer valor
		double valor2 = 0.99; // Double valor2
		boolean valor3 = true; // Boolean valor3
		char valor4 = 'Y'; // Character valor4
		String valor5 = "Tadeu"; // Já é uma classe
		Long valor6 = 100L; // Long valor6
		
		//imprima cada um deles apos a conversao
		
		System.out.println("Integer: " + valor);
		System.out.println("Double: " + valor2);
		System.out.println("Boolean: " + valor3);
		System.out.println("Character: " + valor4);
		System.out.println("String: " + valor5);
		System.out.println("Long: " + valor6);
	}
}
